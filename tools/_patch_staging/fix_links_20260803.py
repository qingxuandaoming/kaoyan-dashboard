def rep(path: pathlib.Path, pairs, must_all=True):
    """pairs: [(old, new)]，逐项替换；返回替换次数。"""
    text = path.read_text(encoding="utf-8")
    n = 0
    for old, new in pairs:
        c = text.count(old)
        if c == 0:
            print(f"  [SKIP] 未找到: {path.name} :: {old[:50]!r}")
            continue
        text = text.replace(old, new)
        n += c
        print(f"  [OK] {path.name}: {c}x  {old[:46]!r} -> {new[:46]!r}")
    if n:
        path.write_text(text, encoding="utf-8")
        if str(path) not in changed_files:
            changed_files.append(str(path))
    return n


