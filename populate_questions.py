# 1. Populate topics
# ──────────────────────────────────────────────────────────────────

def populate_topics(conn):
    """Insert all topics and subtopics from knowledge graphs."""
    cur = conn.cursor()
    count = 0

    for fname in sorted(os.listdir(GRAPH_DIR)):
        if not fname.endswith(".json"):
            continue
        path = os.path.join(GRAPH_DIR, fname)
        with open(path, "r", encoding="utf-8") as f:
            graph = json.load(f)

        subject = graph["subject"]

        for sub_key, sub_data in graph["subs"].items():
            for topic in sub_data["topics"]:
                cur.execute(
                    "INSERT OR REPLACE INTO topics (id, subject, name, chapter, exam_weight, difficulty) "
                    "VALUES (?, ?, ?, ?, ?, ?)",
                    (topic["id"], subject, topic["name"],
                     topic["chapter"], topic["exam_weight"], topic["difficulty"])
                )
                count += 1

                for subtopic in topic.get("subtopics", []):
                    cur.execute(
                        "INSERT OR REPLACE INTO topics (id, subject, name, chapter, exam_weight, difficulty) "
                        "VALUES (?, ?, ?, ?, ?, ?)",
                        (subtopic["id"], subject, subtopic["name"],
                         topic["chapter"], subtopic["weight"], subtopic["difficulty"])
                    )
                    count += 1

    conn.commit()
    print(f"  Inserted {count} topics/subtopics")
    return count


