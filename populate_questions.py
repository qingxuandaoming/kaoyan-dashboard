def _make_q(qid, topic_id, qtype, difficulty, stem, options, answer, explanation, tags, traps=None, exam_frequency=None):
    """Build a question dict."""
    content = {"stem": stem, "explanation": explanation, "tags": tags}
    if exam_frequency is not None:
        content["exam_frequency"] = exam_frequency
    if qtype == "choice":
        content["options"] = options
        content["answer"] = answer
        if traps:
            content["traps"] = traps  # array of strings, one per option; empty string for non-trap positions
    elif qtype == "judge":
        content["options"] = ["正确", "错误"]
        content["answer"] = (answer == 0)  # convert int index to bool: 0→True(正确), 1→False(错误)
    elif qtype == "fill":
        content["answer"] = answer  # string answer
    elif qtype == "short_answer":
        content["answer"] = answer  # string answer
    return {
        "id": qid,
        "topic_id": topic_id,
        "type": qtype,
        "difficulty": difficulty,
        "source": "AI生成",
        "year": None,
        "content": json.dumps(content, ensure_ascii=False),
    }


def _make_card(question_id):
    """Build a card dict for a question."""
    tomorrow = (date.today() + timedelta(days=1)).isoformat()
    card_id = "C-" + question_id[2:]
    return {
        "id": card_id,
        "question_id": question_id,
        "state": 0,
        "difficulty": 0.0,
        "stability": 0.0,
        "due_date": tomorrow,
        "last_review": None,
        "reps": 0,
        "lapses": 0,
        "queue": 0,
        "interval_days": 0,
    }


