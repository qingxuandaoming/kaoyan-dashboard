    all_questions.extend(_gen_politics_questions())
    all_questions.extend(_gen_english_questions())

    for q in all_questions:
        cur.execute(
            "INSERT OR REPLACE INTO questions "
            "(id, topic_id, type, difficulty, source, year, content) "
            "VALUES (?, ?, ?, ?, ?, ?, ?)",
            (q["id"], q["topic_id"], q["type"], q["difficulty"],
             q["source"], q["year"], q["content"])
        )

    conn.commit()
    print(f"  Inserted {len(all_questions)} questions")
    return all_questions


