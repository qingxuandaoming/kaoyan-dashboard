# 4. Create FSRS cards
# ──────────────────────────────────────────────────────────────────

def create_cards_for_questions(conn):
    """Create FSRS cards for all questions."""
    cur = conn.cursor()
    rows = cur.execute("SELECT id FROM questions").fetchall()
    tomorrow = (date.today() + timedelta(days=1)).isoformat()
    count = 0

    for (qid,) in rows:
        card_id = "C-" + qid[2:]
        cur.execute(
            "INSERT OR REPLACE INTO cards "
            "(id, question_id, state, difficulty, stability, due_date, "
            "last_review, reps, lapses, queue, interval_days) "
            "VALUES (?, ?, 0, 0.0, 0.0, ?, NULL, 0, 0, 0, 0)",
            (card_id, qid, tomorrow)
        )
        count += 1

    conn.commit()
    print(f"  Created {count} cards")
    return count


