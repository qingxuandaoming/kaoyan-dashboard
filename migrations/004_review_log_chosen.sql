-- 为什么补这一列：
--   此前答错只留下 rating（1-4），没有「他选了哪一项」。错选只在生成 AI 解析时
--   随请求传给模型，用完即弃、并不落库。结果是周报只能看到「答错了 8 道」，
--   看不到「他把 empty 和 full 搞反了」——而后者才是复盘真正能用的信号，
--   能区分概念混淆 / 计算失误 / 审题错误。
--
-- 取值约定：
--   * 选择题：'A' / 'B' / 'C' / 'D'（单选）。多选或判断按前端实际提交的文本存。
--   * 判断题：前端提交的选项文本（如 '正确' / '错误'）。
--   * 填空、简答：不写（NULL）——作答正文本身在别处，这里只解决"选项题错选"。
--   * 直接看答案（未作答）：NULL。
--
-- 兼容性：只加列，不改类型、不删列、不重命名。存量行该列为 NULL。
-- ============================================================================

ALTER TABLE review_log ADD COLUMN chosen TEXT;
